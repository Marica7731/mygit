#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const {
  DEFAULT_BLOCKLIST_PATH,
  DEFAULT_GENERATED_ASSET_PATH,
  blocklistHash,
  canonicalizeBlocklist,
  loadBlocklist,
  stableJson,
  validateBlocklist,
} = require("./blocked-vtuber-utils");

const ROOT_DIR = path.resolve(__dirname, "..");
const HTML_FILES = ["index.html", "live.html", "today.html", "month.html"];

function main() {
  const sourcePath = path.resolve(ROOT_DIR, parseArg("--source") || DEFAULT_BLOCKLIST_PATH);
  const outPath = path.resolve(ROOT_DIR, parseArg("--out") || DEFAULT_GENERATED_ASSET_PATH);
  const blocklist = loadBlocklist(sourcePath);
  const validation = validateBlocklist(blocklist);
  if (!validation.ok) fail(validation.errors.join("\n"));
  const canonical = canonicalizeBlocklist(blocklist);
  const hash = blocklistHash(blocklist);
  const body = `// Generated by scripts/generate-blocked-vtuber-channels.js. Do not edit by hand.
(function initBlockedVtuberChannels(root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
    return;
  }
  root.BlockedVtuberChannels = factory();
})(typeof globalThis !== "undefined" ? globalThis : window, function createBlockedVtuberChannels() {
  return {
    schemaVersion: ${JSON.stringify(canonical.schemaVersion)},
    listVersion: ${JSON.stringify(canonical.listVersion)},
    updatedAt: ${JSON.stringify(canonical.updatedAt)},
    blocklistHash: "${hash}",
    entries: ${stableJson(canonical.entries)}
  };
});
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, body, "utf8");
  const htmlUpdated = synchronizeHtmlAssetVersions(hash);
  console.log(
    `BLOCKLIST_GENERATE_OK entries=${canonical.entries.length} hash=${hash} out=${path.relative(ROOT_DIR, outPath)} htmlUpdated=${htmlUpdated}`,
  );
}

function synchronizeHtmlAssetVersions(hash) {
  const expectedAsset = `assets/blocked-vtuber-channels.js?v=${hash.slice(0, 12)}`;
  let updatedCount = 0;
  for (const fileName of HTML_FILES) {
    const filePath = path.join(ROOT_DIR, fileName);
    if (!fs.existsSync(filePath)) fail(`${fileName} is missing`);
    const html = fs.readFileSync(filePath, "utf8");
    const updated = html.replace(/assets\/blocked-vtuber-channels\.js(?:\?v=[^"'\\s>]*)?/gu, expectedAsset);
    if (!updated.includes(expectedAsset)) fail(`${fileName} missing assets/blocked-vtuber-channels.js reference`);
    if (updated !== html) {
      fs.writeFileSync(filePath, updated, "utf8");
      updatedCount += 1;
    }
  }
  return updatedCount;
}

function parseArg(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return "";
  return process.argv[index + 1] || "";
}

function fail(message) {
  console.error(`BLOCKLIST_GENERATE_FAIL ${message}`);
  process.exit(1);
}

if (require.main === module) main();
